Ble.Name = "MyBoard";
var svc = new BleService("180F");
var lvl = svc.AddCharacteristic("2A19", BleProperty.Read | BleProperty.Notify, new byte[] { 90 });
var cmd = svc.AddCharacteristic("12345678-1234-5678-1234-56789ABCDEF0", BleProperty.Write | BleProperty.Read, "idle");
cmd.Description = "Command";
cmd.OnWrite((data, conn) => Console.WriteLine("write " + Encoding.UTF8.GetString(data) + " from " + conn.Address));
lvl.OnSubscribe((conn, flags) => Console.WriteLine("subscribed " + flags));
Ble.AddService(svc);
Ble.OnConnect(c => Console.WriteLine("connect " + c + " mtu " + c.Mtu));
Ble.OnDisconnect((c, reason) => Console.WriteLine("disconnect " + c.Address + " reason " + reason));
Ble.OnEvent((ev, conn, v) => Console.WriteLine("event " + Ble.EventName(ev) + " " + v));
var adv = new BleAdvertisement();
adv.AddServiceUuid("180F");
Console.WriteLine(BitConverter.ToString(adv.Build()) + " / " + BitConverter.ToString(adv.BuildScanResponse()));
Ble.StartAdvertising(adv);
Thread.Sleep(20);
Console.WriteLine("advertising " + Ble.Advertising + " subs " + lvl.Subscribers + " cmd=" + cmd.StringValue);
Console.WriteLine("notified " + lvl.Notify(new byte[] { 89 }));
Console.WriteLine("handles " + svc.Handle + " " + lvl.Handle + " " + cmd.Handle);
foreach (var c in Ble.Connections) c.Disconnect();
Thread.Sleep(10);
Console.WriteLine("advertising again " + Ble.Advertising);
Ble.StopAdvertising();
