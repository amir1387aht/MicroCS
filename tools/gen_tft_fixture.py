#!/usr/bin/env python3
"""Embed exact C# native sprite contract in the real opt-in Arduino fixture."""
from pathlib import Path
import argparse
root = Path(__file__).resolve().parent.parent
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--check', action='store_true')
a = p.parse_args()
source = (root / 'tests/tft/sprite_contract.cs').read_text()
assert ')MCS_SPRITE"' not in source
text = '/* Generated by tools/gen_tft_fixture.py; do not edit. */\n' + 'static const char sprite_contract[] = R"MCS_SPRITE(' + source + ')MCS_SPRITE";\n'
out = root / 'tests/tft/src/sprite_contract.h'
if a.check:
    if not out.exists() or out.read_text() != text:
        raise SystemExit('TFT sprite fixture is stale; run tools/gen_tft_fixture.py')
    print('PASS TFT sprite fixture source parity')
else:
    out.write_text(text)
