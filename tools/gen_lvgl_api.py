#!/usr/bin/env python3
"""Generate an explicit, checked LVGL dispatcher/reference from the reviewed schema.
No LVGL checkout, network, header scraping or runtime FFI is involved in a build.
"""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / 'tools/lvgl_api_schema.json'


def guard(e):
    versions = ' || '.join('LVGL_VERSION_MAJOR == ' + m for m in e['variants'])
    return '(' + versions + ') && (' + e['guard'] + ')'


def variants(e, body):
    out = []
    for i, (major, name) in enumerate(e['variants'].items()):
        out += [('#if' if i == 0 else '#elif') + ' LVGL_VERSION_MAJOR == ' + major, body(major, name)]
    return '\n'.join(out + ['#endif'])


def generate(data):
    apis = data['apis']
    aliases = {}
    for i, e in enumerate(apis):
        for name in {e['name'], *e['variants'].values(), *e.get('aliases', [])}:
            # move_to_index is not an alias of both move foreground/background.
            if 'expression9' in e and name == 'lv_obj_move_to_index':
                continue
            if name in aliases and aliases[name] != i:
                raise ValueError('conflicting alias ' + name)
            aliases[name] = i
    lines = ['/* Generated by tools/gen_lvgl_api.py; edit tools/lvgl_api_schema.json. */',
             f'enum {{ MCS_LV_API_COUNT = {len(apis)} }};',
             'static const struct { const char* name; unsigned short id; } native_api_names[] = {']
    lines += [f'    {{"{name}",{i}}},' for name, i in sorted(aliases.items())]
    lines += ['};', 'static int native_api_find(const char* name) {',
              '    size_t lo=0,hi=sizeof native_api_names/sizeof native_api_names[0];',
              '    while(lo<hi){size_t mid=lo+(hi-lo)/2;int c=strcmp(name,native_api_names[mid].name);',
              '        if(!c)return native_api_names[mid].id;',
              '        if(c<0)hi=mid;else lo=mid+1;}', '    return -1;', '}',
              'static bool native_api_available(int id) { switch(id) {']
    lines += [f'#if {guard(e)}\ncase {i}: return true;\n#endif' for i, e in enumerate(apis)]
    lines += ['default:return false;} }',
              'static bool native_api_prepare(mcs_vm_t* vm,int id,int count,mcs_value_t* args,native_args_t* a) {',
              '    (void)args;(void)a;switch(id) {']
    for i, e in enumerate(apis):
        lines += [f'case {i}: /* {e["name"]} */', f'    if(count!={len(e["args"])})return native_arg_error(vm,"Wrong LVGL argument count");']
        for j, arg in enumerate(e['args']):
            k = arg['kind']
            if k == 'nullable_text':
                lines += [f'    if(mcs_is_null(args[{j}]))a->v[{j}].text=NULL;else if(!native_text_arg(vm,args[{j}],&a->v[{j}].text))return false;']
            elif k == 'text':
                lines += [f'    if(!native_text_arg(vm,args[{j}],&a->v[{j}].text))return false;']
            elif k == 'object':
                null = 'true' if e.get('object_nullable') else 'false'
                lines += [f'    if(!native_object_arg(vm,args[{j}],&a->v[{j}].object,{null}))return false;']
            else:
                lines += [f'    if(!native_number_arg(vm,args[{j}],&a->v[{j}].n,{arg["lo"]},{arg["hi"]},NARG_{k.upper()}))return false;']
        check = e.get('check')
        if check in ('range', 'spin_range'):
            offset = 1 if e['name'] == 'lv_chart_set_range' else 0
            lines += [f'    if(a->v[{offset}].n>=a->v[{offset+1}].n)return native_arg_error(vm,"LVGL minimum must be below maximum");']
        if check in ('digits', 'spin_digits'):
            lines += ['    if(a->v[1].n>a->v[0].n)return native_arg_error(vm,"Spinbox separator exceeds digit count");']
        if check == 'unicode':
            lines += ['    if(a->v[0].n>=0xd800 && a->v[0].n<=0xdfff)return native_arg_error(vm,"Unicode surrogate is not a scalar");', '#if LV_TXT_ENC != LV_TXT_ENC_UTF8', '    if(a->v[0].n>127)return native_arg_error(vm,"Non-UTF8 LVGL host supports ASCII scalars only");', '#endif']
        if check == 'symbol_text':
            lines += ['    if(a->v[0].text && a->v[0].text[0] && (unsigned char)a->v[0].text[0]<0x80)return native_arg_error(vm,"Dropdown symbol needs UTF-8 symbol text, not an image filename/descriptor");']
        if check == 'grid_style':
            lines += ['    if(a->v[1].n!=0)return native_arg_error(vm,"Grid cell placement requires selector 0");']
        if check == 'month':
            lines += ['    if(a->v[0].n<1 || a->v[0].n>9999 || a->v[1].n<1 || a->v[1].n>12)return native_arg_error(vm,\"Calendar month out of range\");']
        if check == 'date':
            lines += ['    if(a->v[0].n<1 || a->v[0].n>9999 || a->v[1].n<1 || a->v[1].n>12 || a->v[2].n<1 || a->v[2].n>31)return native_arg_error(vm,"Calendar date out of range");']
        lines += ['    return true;']
    lines += ['default:return native_arg_error(vm,"Unknown LVGL API ID");} }',
              'static int native_api_execute(session_t* s,slot_t* r,int id,native_args_t* a,native_result_t* out) {',
              '    (void)s;(void)a;(void)out;switch(id) {']
    for i, e in enumerate(apis):
        lines += [f'#if {guard(e)}', f'case {i}: {{ /* {e["name"]} */']
        if e['kinds'] != -1:
            expr = ' && '.join(f'r->kind!={k}' for k in e['kinds'])
            lines += [f'    if({expr})return NERR_KIND;']
        for j, arg in enumerate(e['args']):
            if arg['kind'] == 'object':
                lines += [f'    slot_t* other{j}=a->v[{j}].object ? lookup(s,a->v[{j}].object) : NULL;',
                          f'    if(a->v[{j}].object && !other{j})return NERR_DELETED;']
        check = e.get('check')
        if check in ('spin_range', 'spin_value', 'spin_step'):
            lines += ['    int32_t limit=native_spin_limit(r->spin_digits);']
            if check == 'spin_step':
                lines += ['    if(a->v[0].n>(limit+1)/10)return NERR_RANGE;']
            else:
                for j in range(2 if check == 'spin_range' else 1):
                    lines += [f'    if(a->v[{j}].n < -limit || a->v[{j}].n > limit)return NERR_RANGE;']
        if check == 'spin_digits':
            lines += ['    int32_t limit=native_spin_limit((unsigned)a->v[0].n);',
                      '    int32_t value=lv_spinbox_get_value(r->obj);',
                      '    if(value < -limit || value > limit || lv_spinbox_get_step(r->obj)>(limit+1)/10)return NERR_RANGE;']
        if check == 'parent':
            lines += ['    for(lv_obj_t* p=other0->obj;p;p=lv_obj_get_parent(p))if(p==r->obj)return NERR_CYCLE;',
                      '#if LV_USE_GRID',
                      '    if(!native_grid_existing(s,r->obj,other0->obj,0,0))return NERR_RANGE;', '#endif']
        if check == 'grid_cell':
            lines += ['    if(!native_grid_bounds(s,lv_obj_get_parent(r->obj),a->v[1].n,a->v[2].n,a->v[4].n,a->v[5].n))return NERR_RANGE;']
        if check == 'grid_style':
            lines += [f'    if(!native_grid_existing(s,r->obj,lv_obj_get_parent(r->obj),{e["grid_field"]},a->v[0].n))return NERR_RANGE;']
        if check == 'image_offset':
            lines += ['    if(lv_obj_get_self_width(r->obj)<=0 || lv_obj_get_self_height(r->obj)<=0)return NERR_RANGE;']
        if check == 'textarea':
            lines += ['    if(other0 && other0->kind!=11 && other0->kind!=14)return NERR_KIND;']
        if check == 'button_selection':
            lines += ['    if(a->v[0].n!=-1 && a->v[0].n!=65535 && !native_button_index(r->obj,(unsigned)a->v[0].n))return NERR_RANGE;']
        if check == 'button_index':
            lines += ['    if(!native_button_index(r->obj,(unsigned)a->v[0].n))return NERR_RANGE;']
        if check in ('table_size', 'table_index'):
            n = e['name']
            if check == 'table_size':
                rows = 'a->v[0].n' if n.endswith('row_cnt') else 'mcs_lv_table_rows(r->obj)'
                cols = 'a->v[0].n' if n.endswith('col_cnt') else 'mcs_lv_table_columns(r->obj)'
                lines += [f'    if((uint64_t)({rows})*(uint64_t)({cols})>MCS_LVGL_MAX_TABLE_CELLS)return NERR_RANGE;']
            elif n in ('lv_table_get_cell_value', 'lv_table_has_cell_ctrl'):
                lines += ['    if((uint32_t)a->v[0].n>=mcs_lv_table_rows(r->obj) || (uint32_t)a->v[1].n>=mcs_lv_table_columns(r->obj))return NERR_RANGE;']
            elif n == 'lv_table_get_col_width':
                lines += ['    if((uint32_t)a->v[0].n>=mcs_lv_table_columns(r->obj))return NERR_RANGE;']
            else:
                rows = 'mcs_lv_table_rows(r->obj)'
                cols = 'a->v[0].n+1' if 'col_width' in n else 'a->v[1].n+1'
                if 'cell' in n:
                    rows = 'a->v[0].n+1'
                lines += [f'    if((uint64_t)LV_MAX((uint64_t)({rows}),(uint64_t)mcs_lv_table_rows(r->obj))*(uint64_t)LV_MAX((uint64_t)({cols}),(uint64_t)mcs_lv_table_columns(r->obj))>MCS_LVGL_MAX_TABLE_CELLS)return NERR_RANGE;']
        if 'retained_text' in e:
            lines += [f'    return native_retained_text(s,r,{e["retained_text"]},a->v[0].text);', '}', '#endif']
            continue
        if check == 'selected_text':
            option_getter = 'lv_dropdown_get_options' if e['name'].startswith('lv_dropdown_') else 'lv_roller_get_options'
            lines += ['    /* LVGL 8.1 normalizes NULL options to an empty string; its selected getter still dereferences NULL. */',
                      f'    const char* options={option_getter}(r->obj);',
                      '    if(!options || !options[0])return native_copy_text(s,"",out);',
                      '    size_t capacity=0;while(capacity<MCS_LVGL_MAX_TEXT_BYTES+1u && options[capacity])++capacity;',
                      '    ++capacity; /* full options length bounds any selected line; +1 detects overlong output */',
                      '    out->text=s->host.alloc(s->host.ctx,capacity);',
                      '    if(!out->text)return NERR_MEMORY;',
                      f'    {e["name"]}(r->obj,out->text,(uint32_t)capacity);',
                      '    out->length=strlen(out->text);',
                      '    if(out->length>MCS_LVGL_MAX_TEXT_BYTES)return NERR_TEXT;',
                      '    out->kind=NRET_TEXT;return 0;', '}', '#endif']
            continue
        def call(major, name):
            args = ['r->obj']
            for j, arg in enumerate(e['args']):
                k = arg['kind']
                args.append(f'a->v[{j}].text' if k in ('text','nullable_text') else f'(other{j} ? other{j}->obj : NULL)' if k == 'object' else f'lv_color_hex((uint32_t)a->v[{j}].n)' if k == 'color' else f'a->v[{j}].n')
            call_name={'lv_textarea_set_align':'mcs_lv_textarea_set_align','lv_textarea_add_char':'mcs_lv_textarea_add_scalar','lv_obj_add_flag':'mcs_lv_obj_add_flag','lv_obj_clear_flag':'mcs_lv_obj_remove_flag','lv_obj_remove_flag':'mcs_lv_obj_remove_flag','lv_obj_has_flag':'mcs_lv_obj_has_flag','lv_table_add_cell_ctrl':'mcs_lv_table_add_cell_ctrl'}.get(name,name)
            expr = e.get('expression' + major, call_name + '(' + ','.join(args) + ')')
            result = e['result']
            if result == 'void':
                return '    ' + expr + ';'
            if '*' in result:
                return '    return native_copy_text(s,' + expr + ',out);'
            if result == 'lv_color_t':
                return '    out->number=(int64_t)(mcs_lv_color_rgb(' + expr + ') & 0xffffff);out->kind=NRET_INT;'
            if result == 'bool':
                return '    out->number=' + expr + ';out->kind=NRET_BOOL;'
            extra = '\n    if(out->number==UINT32_MAX || out->number==UINT16_MAX)out->number=-1;' if e.get('sentinel') else ''
            if e.get('none'):
                extra += '\n    if(out->number==' + e['none'] + ')out->number=-1;'
            return '    out->number=' + expr + ';out->kind=NRET_INT;' + extra
        lines += [variants(e, call)]
        if check == 'spin_digits':
            lines += ['    r->spin_digits=(uint8_t)a->v[0].n;']
        lines += ['    return 0;', '}', '#endif']
    lines += ['default:return NERR_UNAVAILABLE;} }']
    consts = data['constants']
    lines += ['static int native_constant_lookup(const char* name,int32_t* value) {',
              '    (void)value; /* values can be runtime layout IDs on older LVGL */']
    # Small separate sorted table and switch: no VM table entries per constant.
    lines += ['    static const char* const names[] = {'] + [f'"{e["name"]}",' for e in consts] + ['    };',
              '    size_t lo=0,hi=sizeof names/sizeof names[0];int found=-1;',
              '    while(lo<hi){size_t mid=lo+(hi-lo)/2;int c=strcmp(name,names[mid]);if(!c){found=(int)mid;break;}if(c<0)hi=mid;else lo=mid+1;}',
              '    switch(found) {']
    for i, e in enumerate(consts):
        lines += [f'#if {guard(e)}', f'case {i}:', variants(e, lambda major, name: '    *value=(int32_t)' + name + ';return 1;'), '#endif']
    lines += ['default:return 0;} }']
    docs = ['# LVGL checked native-call reference', '',
            'Generated by `python3 tools/gen_lvgl_api.py`. This is an explicit allowlist,',
            'not arbitrary FFI and not the entire LVGL API. See [integration](LVGL.md).', '',
            f'{len(apis)} operation families, {len(aliases)} accepted native-name spellings and {len(consts)} named constants.', '',
            'Call `widget.Call("lv_obj_set_width", 80)` or cache `Lvgl.Api(name)` and',
            'pass the returned build-specific integer ID to `widget.Call(id, ...)`.',
            '`Lvgl.HasApi(name)` checks version/config availability. Object arguments',
            'must be live `LvObject` handles; scalar arguments are checked before',
            'taking the GUI lock. Text getters return copied VM strings. No pointer',
            'values are accepted or returned. `Lvgl.Constant(name)` resolves the',
            'current native enum value; `Lvgl.HasConstant(name)` checks availability.', '',
            '## Operations', '', '| API family (aliases in version columns) | LVGL 8 | LVGL 9 | Args after object | Result | Config |', '| --- | --- | --- | --- | --- | --- |']
    for e in apis:
        argtext = ', '.join('LvObject' if a['kind'] == 'object' else 'string/null (owned copy)' if a['kind'] == 'nullable_text' else 'string (copied)' if a['kind'] == 'text' else f'{a["kind"]} {a["lo"]}..{a["hi"]}' for a in e['args']) or 'none'
        docs += ['| `' + e['name'] + '` | ' + e['variants'].get('8', '—') + ' | ' + e['variants'].get('9', '—') + ' | ' + argtext + ' | ' + e['result'].replace('*', r'\*') + ' | ' + e['guard'] + ' |']
    docs += ['', 'Coordinate arguments additionally accept the host encoding returned by',
             '`Lvgl.Percent(-1000..1000)` and `Lvgl.Constant("LV_SIZE_CONTENT")` where',
             'the manifest marks them `coordinate`. Part/selector/state bitfields are',
             'validated separately, not merely by numeric range. Table growth is bounded',
             'by `MCS_LVGL_MAX_TABLE_CELLS` (default 256); copied text is bounded by',
             '`MCS_LVGL_MAX_TEXT_BYTES` (default 4096). Native allocator failure limits',
             'from the integration guide still apply. Range/enum restrictions are part',
             'of this wrapper contract; this does not expose every native argument.', '',
             'Grid cell-style placement requires selector 0 and must fit copied parent',
             'tracks; shrinking grids and reparenting are checked too. Use the separate',
             '`SetGrid` / `SetPoints` copying methods for retained arrays. Image offsets',
             'require nonzero intrinsic image dimensions; native offset normalization',
             'still follows the host version (LVGL 8.0 uses source-size modulo).', '',
             '`lv_textarea_add_char` accepts Unicode scalars (1..0x10ffff, excluding',
             'surrogates), encoded into a copied native text insertion. It does not',
             'accept native packed UTF-8 words; non-UTF8 hosts accept ASCII only.', '',
             'Retained text setters (`lv_textarea_set_accepted_chars`, dropdown',
             '`set_text` / `set_symbol`) own a bounded native copy until replacement',
             'or deletion. Pass null to reset; empty accepted chars also resets the filter.',
             'Dropdown symbols accept UTF-8 symbol text (or empty/null), not image',
             'descriptors or ASCII filenames. Hosts must not replace these owned',
             'pointers behind the binding. Selected-string getters return a copied',
             'VM string with no caller buffer argument and reject overlong output.', '',
             '`SetButtonMap(string[]/List<string>)` owns labels and a terminated native',
             'pointer table. Use `\\n` entries between nonempty rows; do not supply',
             'an empty terminator. At most 256 entries and MAX_TEXT_BYTES total copied',
             'text bytes (including string terminators) are accepted. ButtonMatrix only;',
             'Keyboard owns its mode maps. Replacing a map clears selection.',
             '`SetButtonControls(int[]/List<int>)` copies one native 16-bit control mask',
             'per button (not row separator); its scratch copy is released immediately.',
             '`ButtonCount` works on ButtonMatrix/Keyboard. Use named native control',
             'constants because their bit positions differ between majors. Selection',
             'setter accepts -1 or BTN_NONE to clear; other indices must exist.', '',
             '## Constants', '', '| Name | Config | Majors |', '| --- | --- | --- |']
    docs += [f'| `{e["name"]}` | {e["guard"]} | {", ".join(e["variants"])} |' for e in consts]
    tests = ['/* Generated availability/arity/style smoke cases; semantic tests are separate. */',
             'static const struct { const char* name; bool available; int argc; const char* smoke; } native_cases[] = {']
    for e in apis:
        smoke = None
        if e['name'].startswith('lv_obj_get_style_'):
            smoke = 'probe.Call(\"' + e['name'] + '\",0);'
        elif e['name'].startswith('lv_obj_set_style_'):
            a = e['args'][0]
            value = max(a['lo'], 0)
            if a['kind'] == 'color':
                value = 0xff0000
            if 'zoom' in e['name'] or 'scale_' in e['name']:
                value = 256
            smoke = 'probe.Call(\"' + e['name'] + '\",' + str(value) + ',0);'
        tests += [f'{{\"{e["name"]}\",', '#if ' + guard(e), 'true,', '#else', 'false,', '#endif',
                  str(len(e['args'])) + ',' + (json.dumps(smoke) if smoke else 'NULL') + '},']
    tests += ['};', 'static const struct { const char* name;bool available; } constant_cases[] = {']
    for e in consts:
        tests += [f'{{\"{e["name"]}\",', '#if ' + guard(e), 'true,', '#else', 'false,', '#endif', '},']
    tests += ['};']
    return {'modules/drivers/mcs_lvgl_api.inc': '\n'.join(lines) + '\n',
            'docs/LVGL_NATIVE_API.md': '\n'.join(docs) + '\n',
            'tests/lvgl/native_cases.inc': '\n'.join(tests) + '\n'}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    data = json.loads(SCHEMA.read_text())
    outputs = generate(data)
    for path, text in outputs.items():
        target = ROOT / path
        if a.check:
            if not target.exists() or target.read_text() != text:
                raise SystemExit(path + ' is stale; run tools/gen_lvgl_api.py')
        else:
            target.write_text(text)
    print('LVGL generated API/reference: ' + ('checked' if a.check else 'updated'))


if __name__ == '__main__':
    main()
